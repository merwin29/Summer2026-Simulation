function clearSubsystem(subPath)
Simulink.SubSystem.deleteContents(subPath);
end

function addModelAnnotation(systemName, annotationText, position, fontSize)
annotation = Simulink.Annotation(systemName, annotationText);
annotation.Position = position;
annotation.FontSize = fontSize;
end

function setMatlabFunctionScript(blockPath, lines)
root = sfroot;
chart = root.find("-isa", "Stateflow.EMChart", "Path", char(blockPath));
if isempty(chart)
    error("Could not find MATLAB Function chart at %s", blockPath);
end
chart.Script = strjoin(lines, newline);
end

function lines = controllerScript(params)
lines = [
"function [axleTorque_Nm, brakeForce_N] = f(targetSpeed_mps, actualSpeed_mps)"
"%#codegen"
"% Negative axle torque is the forward direction for this Simscape block orientation."
"torqueGain = " + num2str(params.torqueGain, "%.12g") + ";"
"brakeGain = " + num2str(params.brakeGain, "%.12g") + ";"
"maxDriveTorque_Nm = " + num2str(params.maxDriveTorque_Nm, "%.12g") + ";"
"maxBrakeForce_N = " + num2str(params.maxBrakeForce_N, "%.12g") + ";"
"speedError = targetSpeed_mps - actualSpeed_mps;"
"driveTorque = min(max(torqueGain * speedError, 0.0), maxDriveTorque_Nm);"
"brakeForce_N = 0.0;"
"axleTorque_Nm = -driveTorque;"
"end"];
end
