function [modelName, modelPath] = buildStage12PhysicsKinematicsBridgeModel(params)
%BUILDSTAGE12PHYSICSKINEMATICSBRIDGEMODEL Build Stage 12 Simulink model.
%
% The model intentionally contains two independent demonstrations:
%   - a Simscape Driveline longitudinal haul-truck plant
%   - a Robotics System Toolbox Turtle-style kinematic plant

modelName = "HaulagePhysicsKinematicsBridge";
modelPath = params.modelPath;
modelDir = fileparts(modelPath);
if ~isfolder(modelDir)
    mkdir(modelDir);
end

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
if isfile(modelPath)
    delete(modelPath);
end

load_system("simulink");
load_system("sdl_lib");
load_system("fl_lib");
load_system("nesl_utility");
load_system("robotmobilelib");

new_system(modelName);
open_system(modelName);
loaderCallback = [
    "stage12ModelFile = get_param(bdroot, 'FileName');"
    "stage12ProjectRoot = fileparts(fileparts(stage12ModelFile));"
    "addpath(stage12ProjectRoot);"
    "loadStage12PhysicsKinematicsBridgeInputs(stage12ProjectRoot);"
    "clear stage12ModelFile stage12ProjectRoot"];
set_param(modelName, ...
    "StopTime", num2str(params.stopTime_s), ...
    "Solver", "ode23t", ...
    "MaxStep", "0.05", ...
    "SignalLogging", "on", ...
    "PostLoadFcn", strjoin(loaderCallback, newline), ...
    "InitFcn", strjoin(loaderCallback, newline));

addModelAnnotation(modelName, ...
    "Stage 12 bridge: Simscape Driveline longitudinal haul-truck plant + Robotics kinematic Turtle robot handoff.", ...
    [40 25 780 55], 12);

add_block("simulink/Ports & Subsystems/Subsystem", modelName + "/Full-Scale Haul Truck Longitudinal Plant", ...
    "Position", [70 110 520 410]);
add_block("simulink/Ports & Subsystems/Subsystem", modelName + "/Turtle Robot Kinematic Plant", ...
    "Position", [610 110 1060 410]);

buildLongitudinalSubsystem(modelName + "/Full-Scale Haul Truck Longitudinal Plant", params);
buildTurtleSubsystem(modelName + "/Turtle Robot Kinematic Plant");

save_system(modelName, modelPath);
fprintf("Generated Stage 12 physics/kinematics bridge model: %s\n", modelPath);
end

